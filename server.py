from fastapi import FastAPI, File, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from ultralytics import YOLO
from PIL import Image
import io

app = FastAPI()

# GitHub Pages'dan keladigan so'rovlarga ruxsat berish
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

# YOLOv8 nano modelini yuklash (birinchi marta avtomatik yuklab oladi)
model = YOLO("yolov8n.pt")

@app.post("/detect")
async def detect_obstacle(file: UploadFile = File(...)):
    image_bytes = await file.read()
    img = Image.open(io.BytesIO(image_bytes)).convert("RGB")

    results = model(img, conf=0.45)
    detections = []

    for r in results:
        for box in r.boxes:
            cls_id = int(box.cls[0])
            label = model.names[cls_id]
            conf = round(float(box.conf[0]) * 100, 1)
            detections.append({
                "label": label,
                "confidence": conf
            })

    if not detections:
        return {"detected": False, "message": "전방 보행로 안전 (장애물 미검출)"}

    # Eng yuqori ishonchlilikka ega ob'ektni qaytarish
    best = max(detections, key=lambda x: x["confidence"])
    return {
        "detected": True,
        "type": f"AI 검출: {best['label']}",
        "confidence": best["confidence"],
        "message": f"⚠️ 전방 '{best['label']}' 장애물 검출 ({best['confidence']}%)"
    }

import subprocess, time, threading, uvicorn

# FastAPI serverni alohida oqimda (thread) 8000-portda ishga tushirish
def run_server():
    uvicorn.run(app, host="0.0.0.0", port=8000, log_level="warning")

threading.Thread(target=run_server, daemon=True).start()
time.sleep(2)

